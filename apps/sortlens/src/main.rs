//! Sortlens: the desktop application.
//!
//! `main` creates the window, applies the title-bar policy, opens the settings store and hands
//! control to [`App`]. Everything else lives in the crates.

#![forbid(unsafe_code)]

mod settings;

mod sync;

use craft_settings::{Location, store::SettingsStore};
use craft_window::Prefix;
use craft_window::policy::{Backend, Frame, TitleBarPref, apply as apply_titlebar, decide_for};
use settings::Prefs;
use sortlens_engine::{Engine, Sort};
use sortlens_ui::shell::ExportReceipt;
use sortlens_ui::{Action, Density, ThemeKind, Thumbnails, UiState, apply as apply_theme, i18n};
use sync::Sync;

/// The top bar's leading inset: how much room the frame needs before the app paints anything.
///
/// macOS keeps its traffic lights over the app's bar (`Frame::Inset`) and hands back the strip
/// they occupy, so the mark starts after that strip. Windows and Linux have no leading controls —
/// the app's own three buttons sit at the trailing end — so the bar's ordinary margin is enough.
/// Giving them the traffic-light strip left a 78-point gap with nothing in it.
fn title_inset(frame: &Frame) -> f32 {
    match frame {
        Frame::Inset(mac) => mac.leading,
        Frame::Integrated(_) | Frame::Native => 10.0,
    }
}

/// The app bar's height, when the frame paints its own title strip.
///
/// macOS puts the traffic lights at a fixed fourteen points from the top. On a taller app bar the
/// controls below them read as a second, misaligned row; asking the shell for a 28-point bar puts
/// its centre on the lights' own line. A frame without an inset strip gets `None`, so the shell
/// keeps its normal height.
fn title_bar_height(frame: &Frame) -> Option<f32> {
    match frame {
        Frame::Inset(mac) => Some((mac.centre_from_top * 2.0).max(28.0)),
        Frame::Integrated(_) | Frame::Native => None,
    }
}

fn folder_name(path: &str) -> String {
    path.trim_end_matches(['/', '\\'])
        .rsplit(['/', '\\'])
        .next()
        .filter(|name| !name.is_empty())
        .unwrap_or(path)
        .to_string()
}

/// Where the catalog lives. One library per user for now; libraries become a list in M5.
fn library_dir() -> std::path::PathBuf {
    if let Ok(dir) = std::env::var("SORTLENS_LIBRARY_DIR")
        && !dir.trim().is_empty()
    {
        return std::path::PathBuf::from(dir);
    }
    let base = if cfg!(target_os = "macos") {
        home().join("Library").join("Application Support")
    } else if cfg!(windows) {
        std::env::var_os("APPDATA")
            .map(std::path::PathBuf::from)
            .unwrap_or_else(|| home().join("AppData").join("Roaming"))
    } else {
        std::env::var_os("XDG_DATA_HOME")
            .map(std::path::PathBuf::from)
            .unwrap_or_else(|| home().join(".local").join("share"))
    };
    base.join("Sortlens").join("Library")
}

/// Thumbnail cache, next to the library and safe to delete.
fn cache_dir() -> std::path::PathBuf {
    library_dir()
        .parent()
        .map(|base| base.join("Cache").join("thumbs"))
        .unwrap_or_else(|| std::path::PathBuf::from("thumbs"))
}

fn home() -> std::path::PathBuf {
    std::env::var_os("HOME")
        .map(std::path::PathBuf::from)
        .unwrap_or_else(|| std::path::PathBuf::from("."))
}

/// The window icon, generated by the build script from the one drawing in `sortlens-icon`.
///
/// A PNG is not decoded here: the build writes raw RGBA, so the app needs no image decoder to show its own
/// face. `sortlens-icon`'s tests decode the PNG version, which is the same pixels.
fn window_icon() -> egui::IconData {
    const EDGE: u32 = match u32::from_str_radix(env!("SORTLENS_ICON_EDGE"), 10) {
        Ok(edge) => edge,
        Err(_) => 0,
    };
    egui::IconData {
        rgba: include_bytes!(concat!(env!("OUT_DIR"), "/icon.rgba")).to_vec(),
        width: EDGE,
        height: EDGE,
    }
}

fn main() -> eframe::Result {
    let decision = decide_for(Prefix::new("SORTLENS"), Backend::from_env(), TitleBarPref::Integrated);
    let inset = title_inset(&decision.frame);
    let title_bar_h = title_bar_height(&decision.frame);
    // Only a frame the app draws leaves the window's three buttons to the app: the system title bar
    // draws its own, and macOS keeps its traffic lights over the app's bar (`Frame::Inset`).
    let captions = matches!(decision.frame, Frame::Integrated(_));

    let viewport = apply_titlebar(
        egui::ViewportBuilder::default()
            .with_icon(window_icon())
            .with_title("Sortlens")
            .with_inner_size([1280.0, 800.0])
            .with_min_inner_size([880.0, 560.0]),
        &decision.frame,
    );

    let options = eframe::NativeOptions {
        viewport,
        ..Default::default()
    };
    eframe::run_native(
        "Sortlens",
        options,
        Box::new(move |cc| Ok(Box::new(App::new(cc, inset, captions, title_bar_h)))),
    )
}

/// The application: one engine, one shell, one settings store.
struct App {
    engine: Engine,
    ui: UiState,
    store: SettingsStore<Prefs>,
    applied_theme: ThemeKind,
    thumbs: Thumbnails,
    /// The quit guard has been answered, so the next close goes through.
    confirmed_close: bool,
    /// The library's sync server, spawned on demand and stopped with the window.
    sync: Sync,
}

impl App {
    fn new(cc: &eframe::CreationContext<'_>, title_inset: f32, captions: bool, title_bar_h: Option<f32>) -> Self {
        // Before the first frame, so no frame is drawn in a font that is about to be replaced. With
        // no craft-fonts checkout this is a no-op and egui's own faces stay.
        let faces = sortlens_ui::fonts::install(&cc.egui_ctx);
        if faces > 0 {
            eprintln!(
                "sortlens: {} craft-font face(s) embedded ({})",
                faces,
                sortlens_ui::fonts::families().join(", ")
            );
        }
        let (store, report) = SettingsStore::<Prefs>::open(Location::Auto);
        let kind = ThemeKind::from_id(&store.get().appearance.theme);
        let saved_sort = Sort::parse(&store.get().library.sort);
        apply_theme(&cc.egui_ctx, kind);

        let mut ui = UiState::new(kind, title_inset);
        ui.captions = captions;
        ui.title_bar_h = title_bar_h;
        ui.density = Density::from_id(&store.get().appearance.density);
        ui.grid_mode = sortlens_ui::GridMode::from_id(&store.get().appearance.grid);
        ui.motion = sortlens_ui::Motion::from_id(&store.get().appearance.motion);
        ui.sort = saved_sort;
        ui.library_sort = saved_sort;
        // The interface language is a setting, not a session default (SL-L07): it was chosen
        // deliberately once, and it stays until it is changed. An unknown code reads as English.
        if let Some(lang) = sortlens_ui::i18n::from_code(&store.get().appearance.language) {
            sortlens_ui::i18n::set_current(lang);
            sortlens_ui::i18n::apply_direction(&cc.egui_ctx);
        }
        if report.has_problems() {
            ui.notice(i18n::tr("Settings could not be read in full; defaults are in use"));
        }

        let engine = match Engine::open(library_dir()) {
            Ok(engine) => engine,
            Err(error) => {
                ui.notice(i18n::fmt(
                    "The library could not be opened: {error}",
                    &[("error", &error.to_string())],
                ));
                Engine::new()
            }
        };
        // The model downloader's consent is a setting, not a session default: it was switched on
        // deliberately once, and it stays on until it is switched off.
        let mut engine = engine;
        let consent = store.get().ai.download_consent;
        engine.set_models_consent(consent);
        // The update check's consent, the same way (SL-I10).
        engine.set_update_consent(store.get().updates.check_consent);

        Self {
            engine,
            ui,
            store,
            applied_theme: kind,
            thumbs: Thumbnails::new(cache_dir()),
            confirmed_close: false,
            sync: Sync::new(),
        }
    }

    /// Run the command the engine built for "show this file on disk".
    ///
    /// The engine refuses a file that is no longer there, so a failure here is about the desktop
    /// (no handler, a sandbox) rather than about the library, and the message says which.
    fn show_in_folder(&mut self, id: sortlens_core::PhotoId) {
        self.spawn(sortlens_engine::RevealMode::Reveal, id);
    }

    /// Hand the file to whatever the desktop opens it with.
    fn open_externally(&mut self, id: sortlens_core::PhotoId) {
        self.spawn(sortlens_engine::RevealMode::Open, id);
    }

    fn spawn(&mut self, mode: sortlens_engine::RevealMode, id: sortlens_core::PhotoId) {
        let built = match self.engine.reveal_target(id, mode) {
            Ok(built) => built,
            Err(error) => {
                self.ui.notice(error.to_string());
                return;
            }
        };
        match std::process::Command::new(&built.program)
            .args(&built.args)
            .stdout(std::process::Stdio::null())
            .stderr(std::process::Stdio::null())
            .status()
        {
            // Explorer returns 1 even when it did the job, so a non-zero exit is reported as the
            // command failing to start only when the program itself could not be run at all.
            Ok(_) => {
                let folder_only = sortlens_core::Desktop::current().is_some_and(|desktop| !sortlens_core::reveal::reveal_selects(desktop))
                    && mode == sortlens_engine::RevealMode::Reveal;
                let note = if folder_only {
                    i18n::tr("Opened the containing folder — this desktop cannot select a file in it").to_string()
                } else {
                    built.display()
                };
                self.ui.notice(note);
            }
            Err(error) => self.ui.notice(i18n::fmt(
                "Could not run {program}: {error}",
                &[("program", &built.program), ("error", &error.to_string())],
            )),
        }
    }

    fn apply(&mut self, ctx: &egui::Context, action: Action) {
        match action {
            Action::SetDensity(density) => {
                self.store.update(|prefs| prefs.appearance.density = density.id().to_owned());
            }
            Action::SetGrid(mode) => {
                self.store.update(|prefs| prefs.appearance.grid = mode.id().to_owned());
            }
            Action::SetMotion(motion) => {
                self.store.update(|prefs| prefs.appearance.motion = motion.id().to_owned());
            }
            Action::SetLanguage(code) => {
                self.store.update(|prefs| prefs.appearance.language = code);
            }
            Action::SetTheme(kind) => {
                if kind != self.applied_theme {
                    apply_theme(ctx, kind);
                    self.applied_theme = kind;
                    self.store.update(|prefs| prefs.appearance.theme = kind.id().to_owned());
                }
            }
            Action::Quit => {
                // The guard has already been answered; do not ask again on the way out.
                self.confirmed_close = true;
                let _ = self.store.flush();
                ctx.send_viewport_cmd(egui::ViewportCommand::Close);
            }
            // The three the bar draws when the frame is the app's. They are viewport commands, which
            // is why the shell asks rather than sends: the window is the host's.
            Action::MinimizeWindow => ctx.send_viewport_cmd(egui::ViewportCommand::Minimized(true)),
            Action::ToggleZoom => {
                let maximized = ctx.input(|input| input.viewport().maximized).unwrap_or(false);
                ctx.send_viewport_cmd(egui::ViewportCommand::Maximized(!maximized));
            }
            // The system's own close request, not `Quit`: `Quit` says the guard was already answered,
            // and this button has not asked. The window's close handling below runs its guard.
            Action::CloseWindow => ctx.send_viewport_cmd(egui::ViewportCommand::Close),
            Action::Notice(text) => self.ui.notice(text),
            Action::Reveal(id) => self.show_in_folder(id),
            Action::OpenExternal(id) => self.open_externally(id),
            Action::PickFolder => {
                if let Some(folder) = rfd::FileDialog::new()
                    .set_title(i18n::tr("Add a folder to the library"))
                    .pick_folder()
                {
                    let path = folder.to_string_lossy().to_string();
                    match self.engine.begin_scan(path.clone()) {
                        Ok(()) => self.ui.notice(i18n::fmt("Indexing {folder}…", &[("folder", &folder_name(&path))])),
                        Err(error) => self.ui.notice(error.to_string()),
                    }
                }
            }
            Action::MovePicks(ids) => {
                if ids.is_empty() {
                    self.ui.notice(i18n::tr("Pick a photo first"));
                    return;
                }
                if let Some(folder) = rfd::FileDialog::new().set_title(i18n::tr("Move the picks into…")).pick_folder() {
                    let dest = folder.to_string_lossy().to_string();
                    match self.engine.move_picks(&dest, &ids) {
                        Ok(count) => {
                            // The receipt dialog words the same move; the status line asks it, so the
                            // two cannot disagree about the folder or the count.
                            let headline = self.engine.move_receipts().last().map(sortlens_ui::shell::move_receipt_headline);
                            self.ui.move_receipt = self.engine.move_receipts().last().map(|receipt| receipt.id);
                            self.ui
                                .notice(headline.unwrap_or_else(|| i18n::moved_headline(count, &folder_name(&dest))))
                        }
                        Err(error) => self.ui.notice(error.to_string()),
                    }
                }
            }
            Action::Export(ids, spec) => {
                if ids.is_empty() {
                    self.ui.notice(i18n::tr("Pick a photo first"));
                    return;
                }
                if let Some(folder) = rfd::FileDialog::new().set_title(i18n::tr("Export into…")).pick_folder() {
                    match self.engine.begin_export(&folder, &ids, &spec) {
                        Ok(0) => {
                            let receipt = self.engine.last_export().map(ExportReceipt::from_report).unwrap_or(ExportReceipt {
                                written: 0,
                                skipped: 0,
                                failed: 0,
                                bytes: 0,
                                dest: folder.clone(),
                            });
                            self.ui.export_open = false;
                            self.ui.export_receipt = Some(receipt);
                        }
                        Ok(planned) => {
                            self.ui
                                .notice(i18n::fmt("Exporting {n} file(s)…", &[("n", &i18n::count(planned as u64))]));
                        }
                        Err(error) => self.ui.notice(error.to_string()),
                    }
                }
            }
            Action::StartSuggest => match self.engine.begin_batch_suggest() {
                Ok(0) => self.ui.notice(i18n::tr("Nothing to suggest: the library is empty")),
                Ok(count) => self
                    .ui
                    .notice(i18n::fmt("Looking at {n} photo(s)…", &[("n", &i18n::count(count as u64))])),
                Err(error) => self.ui.notice(error.to_string()),
            },
            Action::CancelSuggest => {
                self.engine.cancel_batch();
                self.ui.notice(i18n::tr("Stopping the suggestion pass"));
            }
            Action::ClearSuggest => {
                self.engine.clear_batch();
                self.ui.notice(i18n::tr("Cleared the suggestions"));
            }
            Action::SaveShortcuts(profiles) => {
                self.store.update(|prefs| prefs.shortcuts = profiles);
            }
            Action::ImportShortcuts => {
                let Some(path) = rfd::FileDialog::new()
                    .set_title(i18n::tr("Import a shortcut set"))
                    .add_filter(i18n::tr("Shortcut set"), &["json"])
                    .pick_file()
                else {
                    return;
                };
                match std::fs::read_to_string(&path) {
                    Ok(text) => self.ui.pending_shortcut_import = Some(text),
                    Err(error) => self
                        .ui
                        .notice(i18n::fmt("The set could not be read: {error}", &[("error", &error.to_string())])),
                }
            }
            Action::ExportShortcuts(name, json) => {
                let Some(path) = rfd::FileDialog::new()
                    .set_title(i18n::tr("Export a shortcut set"))
                    .set_file_name(format!("{name}.json"))
                    .add_filter(i18n::tr("Shortcut set"), &["json"])
                    .save_file()
                else {
                    return;
                };
                match std::fs::write(&path, json) {
                    Ok(()) => self.ui.notice(i18n::fmt("Wrote “{name}”", &[("name", &name)])),
                    Err(error) => self
                        .ui
                        .notice(i18n::fmt("The set could not be written: {error}", &[("error", &error.to_string())])),
                }
            }
            Action::SetPack(name, on) => match self.engine.set_pack(&name, on) {
                Ok(true) => {
                    // The change report's own sentence, so the toast and the report word a pack the
                    // same way, and a language translates the row once.
                    let words = if on {
                        i18n::fmt("Switched on the “{name}” keyword pack", &[("name", &name)])
                    } else {
                        i18n::fmt("Switched off the “{name}” keyword pack", &[("name", &name)])
                    };
                    self.ui.notice(words);
                }
                Ok(false) => {}
                Err(error) => self.ui.notice(error.to_string()),
            },
            Action::AcceptSuggestion(id, tag) => match self.engine.accept_suggestion(id, &tag) {
                Ok(true) => self.ui.notice(i18n::fmt("Tagged “{tag}”", &[("tag", &tag)])),
                Ok(false) => self.ui.notice(i18n::fmt("Already tagged “{tag}”", &[("tag", &tag)])),
                Err(error) => self.ui.notice(error.to_string()),
            },
            Action::UndoMove(id) => match self.engine.undo_move(id) {
                Ok(count) => {
                    self.ui.move_receipt = None;
                    self.ui
                        .notice(i18n::fmt("Put {n} photo(s) back", &[("n", &i18n::count(count as u64))]));
                }
                Err(error) => self.ui.notice(error.to_string()),
            },
            Action::ExportHistory => {
                if let Some(path) = rfd::FileDialog::new()
                    .set_title(i18n::tr("Save the change report"))
                    .set_file_name("sortlens-change-report.txt")
                    .add_filter(i18n::tr("Text"), &["txt"])
                    .save_file()
                {
                    match self.engine.export_history(&path) {
                        Ok(lines) => self.ui.notice(i18n::fmt(
                            "Wrote {lines} line(s) to {folder}",
                            &[
                                ("lines", &i18n::count(lines as u64)),
                                ("folder", &folder_name(&path.to_string_lossy())),
                            ],
                        )),
                        Err(error) => self.ui.notice(error.to_string()),
                    }
                }
            }
            Action::RemapRoot(from) => {
                if let Some(folder) = rfd::FileDialog::new()
                    .set_title(i18n::tr("Where does this folder live now?"))
                    .pick_folder()
                {
                    let to = folder.to_string_lossy().to_string();
                    match self.engine.remap_root(&from, &to) {
                        Ok(count) => self.ui.notice(i18n::fmt(
                            "Repointed {n} photo(s) to {folder}",
                            &[("n", &i18n::count(count as u64)), ("folder", &folder_name(&to))],
                        )),
                        Err(error) => self.ui.notice(error.to_string()),
                    }
                }
            }
            Action::Rescan(root) => match self.engine.begin_scan(root.clone()) {
                Ok(()) => self
                    .ui
                    .notice(i18n::fmt("Rescanning {folder}…", &[("folder", &folder_name(&root))])),
                Err(error) => self.ui.notice(error.to_string()),
            },
            Action::SetSort(sort) => {
                self.ui.sort = sort;
                self.store.update(|prefs| prefs.library.sort = sort.id().to_owned());
            }
            Action::SetSidecars(on) => self.ui.notice(if on {
                i18n::tr("Writing XMP sidecars beside photos")
            } else {
                i18n::tr("Sidecar writing off; changes stay in the catalog")
            }),
            Action::SetModelConsent(on) => {
                self.store.update(|prefs| prefs.ai.download_consent = on);
                self.ui.notice(if on {
                    i18n::tr("Model downloads allowed — nothing downloads until you install one")
                } else {
                    i18n::tr("Model downloads switched off")
                });
            }
            Action::SetUpdateConsent(on) => {
                self.store.update(|prefs| prefs.updates.check_consent = on);
                self.ui.notice(if on {
                    i18n::tr("Update checks allowed — nothing is fetched until you run one")
                } else {
                    i18n::tr("Update checks switched off")
                });
            }
            Action::Backup => {
                if let Some(path) = rfd::FileDialog::new()
                    .set_title(i18n::tr("Back up the Sortlens library"))
                    .set_file_name("sortlens-library.backup")
                    .add_filter(i18n::tr("Sortlens backup"), &["backup"])
                    .save_file()
                {
                    match self.engine.export_backup(&path) {
                        Ok(files) => self
                            .ui
                            .notice(i18n::fmt("Backed up {files} file(s)", &[("files", &i18n::count(files as u64))])),
                        Err(error) => self.ui.notice(error.to_string()),
                    }
                }
            }
            Action::RestoreBackup => {
                let Some(path) = rfd::FileDialog::new()
                    .set_title(i18n::tr("Choose a Sortlens backup"))
                    .add_filter(i18n::tr("Sortlens backup"), &["backup"])
                    .pick_file()
                else {
                    return;
                };
                let Some(dest) = rfd::FileDialog::new()
                    .set_title(i18n::tr("Where should the restored library go?"))
                    .pick_folder()
                else {
                    return;
                };
                match sortlens_engine::Engine::import_backup(&path, &dest) {
                    Ok(files) => {
                        let dest = folder_name(&dest.to_string_lossy());
                        self.ui.notice(i18n::fmt(
                            "Restored {files} file(s) into {folder} — open that folder to use it",
                            &[("files", &i18n::count(files as u64)), ("folder", &dest)],
                        ));
                    }
                    Err(error) => self.ui.notice(error.to_string()),
                }
            }
            Action::RemoveRoot(root) => match self.engine.remove_root(&root) {
                Ok(count) => self.ui.notice(i18n::fmt(
                    "Removed {n} photos from {folder}",
                    &[("n", &i18n::count(count as u64)), ("folder", &folder_name(&root))],
                )),
                Err(error) => self.ui.notice(error.to_string()),
            },
            Action::ServerStart => match self.sync.start(&library_dir()) {
                Ok(()) => self
                    .ui
                    .notice(i18n::tr("Serving the library — the pairing code is in Settings → Sync & devices")),
                Err(error) => self.ui.notice(error),
            },
            Action::ServerStop => {
                self.sync.stop();
                self.ui
                    .notice(i18n::tr("The server is stopped; the library's write lock is free again"));
            }
            Action::ServerRevoke(token) => match self.sync.revoke(&library_dir(), &token) {
                Ok(()) => self
                    .ui
                    .notice(i18n::tr("The device's token is removed; it cannot call this library any more")),
                Err(error) => self.ui.notice(error),
            },
            // The phone's section is gated on the phone width, so these cannot come from this
            // host's interface; if one ever does, it is answered rather than silently dropped.
            Action::SendPair { .. } | Action::SendTest { .. } | Action::SendForget | Action::SendToDesktop(..) | Action::SendCancel => self
                .ui
                .notice(i18n::tr("Send to desktop is the phone app's; this library is the desktop")),
        }
    }
}

impl eframe::App for App {
    fn ui(&mut self, ui: &mut egui::Ui, frame: &mut eframe::Frame) {
        let ctx = ui.ctx().clone();
        // The online Places map draws through egui-wgpu. The host is the only owner of that renderer; the shell
        // keeps the handle for the frames that need it, and Places stays on its offline map when there is none.
        self.ui.places_render.set(frame.wgpu_render_state());

        let tick = self.store.tick(std::time::Instant::now());
        if let Some(deadline) = tick.next_deadline {
            ctx.request_repaint_after(deadline.saturating_duration_since(std::time::Instant::now()));
        }

        // The export worker reports on its own thread; this is the only place that notices it
        // finished, so the dialog can show the receipt without the UI knowing about threads.
        if let Some(report) = self.engine.poll_export() {
            self.ui.export_open = false;
            if self.ui.export_receipt.is_none() {
                self.ui.export_receipt = Some(ExportReceipt::from_report(&report));
            }
            ctx.request_repaint();
        }

        // The sync server is the host's to feed: its state is process and file knowledge the
        // shell cannot reach, read only while the Settings dialog can show it. A device that
        // pairs mid-dialog is on the next frame's list.
        if self.ui.settings_open {
            self.ui.server = self.sync.surface(&library_dir(), true);
        }

        // The suggestion pass reports on its own thread; notice it finished where the export is noticed.
        if let Some(count) = self.engine.poll_batch() {
            self.ui.notice(i18n::fmt(
                "{n} photo(s) have something to suggest",
                &[("n", &i18n::count(count as u64))],
            ));
            ctx.request_repaint();
        }
        if self.engine.batch_progress().is_some() {
            ctx.request_repaint_after(std::time::Duration::from_millis(120));
        }

        let actions = sortlens_ui::show(ui, &mut self.ui, &mut self.engine, &mut self.thumbs);
        for action in actions {
            self.apply(&ctx, action);
        }

        if ctx.input(|input| input.viewport().close_requested()) {
            if !self.confirmed_close && self.engine.has_unsaved() {
                // Hold the close, ask, and let the dialog decide.
                self.ui.quit_open = true;
                ctx.send_viewport_cmd(egui::ViewportCommand::CancelClose);
            } else {
                let _ = self.engine.close();
                let _ = self.store.flush();
            }
            // The server holds the library's write lock; it stops with the window either way.
            self.sync.stop();
        }

        if let sortlens_engine::Effect::ShowView(view) = self.engine.last_effect() {
            match view {
                // A view named by an engine command is a view the window opens; the shell's own
                // `activate_view` is not reachable from here, so the two views that need preparation
                // (Compare's second pane, Similar's hashes) arrive through the same commands the
                // palette and the bottom bar use.
                "detail" => self.ui.view = sortlens_ui::View::Detail,
                // Compare needs a second photograph, and only the shell can pick one: the same helper the
                // Compare tab and the C key use, so the command lands on a real pair or on a notice.
                "compare" => sortlens_ui::toggle_compare(&mut self.ui, &self.engine),
                "softFocus" => self.ui.view = sortlens_ui::View::SoftFocus,
                "places" => self.ui.view = sortlens_ui::View::Places,
                "similar" => self.ui.view = sortlens_ui::View::Similar,
                "insights" => self.ui.view = sortlens_ui::View::Insights,
                _ => {}
            }
        }
        if self.engine.last_effect() == sortlens_engine::Effect::Quit {
            let _ = self.engine.close();
            let _ = self.store.flush();
            ctx.send_viewport_cmd(egui::ViewportCommand::Close);
        }
    }
}

