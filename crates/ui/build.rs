//! Embed the optional craft-fonts faces, when the machine has a checkout.
//!
//! The fonts live in a separate repository, so the app never depends on it in `Cargo.toml`: that
//! would make every build — offline, in a fork, on a mirror — fetch it. The build input is an
//! environment variable instead, and **unset is a supported configuration**: the table is empty and
//! the app runs on egui's own fonts, which is what CI does.
//!
//! ```sh
//! git clone https://github.com/storytold/craft-fonts .fonts/craft-fonts
//! CRAFT_FONTS_DIR=$PWD/.fonts/craft-fonts cargo build -p sortlens
//! CRAFT_FONTS_REQUIRED=1 CRAFT_FONTS_DIR=… cargo build --release   # fails rather than ship without
//! ```
//!
//! The manifest format is craft-fonts': `family | style | file | scripts | …`, and this file reads it
//! directly rather than through a build dependency, so the build script stays dependency-free.

#![forbid(unsafe_code)]

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    println!("cargo::rerun-if-changed=build.rs");
    println!("cargo::rerun-if-env-changed=CRAFT_FONTS_DIR");
    println!("cargo::rerun-if-env-changed=CRAFT_FONTS_REQUIRED");

    let required = std::env::var_os("CRAFT_FONTS_REQUIRED").is_some();
    let mut table = String::from("// Generated by crates/ui/build.rs. Empty when CRAFT_FONTS_DIR is unset.\n");
    table.push_str("pub static CRAFT_FONTS: &[CraftFont] = &[\n");

    match std::env::var_os("CRAFT_FONTS_DIR").map(PathBuf::from) {
        Some(dir) => match faces(&dir) {
            Ok(entries) => table.push_str(&entries),
            Err(error) if required => {
                println!("cargo::error=CRAFT_FONTS_DIR={}: {error}", dir.display());
            }
            Err(error) => {
                println!(
                    "cargo::warning=building without craft-fonts: CRAFT_FONTS_DIR={}: {error}",
                    dir.display()
                );
            }
        },
        None if required => {
            println!("cargo::error=CRAFT_FONTS_REQUIRED is set but CRAFT_FONTS_DIR is missing");
        }
        None => {
            println!(
                "cargo::warning=craft-fonts are not embedded (CRAFT_FONTS_DIR is unset); \
                      the app uses its own and system fonts"
            );
        }
    }
    table.push_str("];\n");

    let out = PathBuf::from(std::env::var_os("OUT_DIR").unwrap_or_default()).join("craft_fonts.rs");
    if let Err(error) = std::fs::write(&out, table) {
        println!("cargo::error=writing {}: {error}", out.display());
    }
}

/// One `CraftFont { … }` initialiser per selected manifest line.
fn faces(dir: &Path) -> Result<String, String> {
    let manifest = dir.join("fonts/manifest.txt");
    println!("cargo::rerun-if-changed={}", manifest.display());
    let text = std::fs::read_to_string(&manifest).map_err(|error| format!("{}: {error}", manifest.display()))?;

    let mut out = String::new();
    let mut included: Vec<(&str, &str)> = Vec::new();
    for line in text
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
    {
        let fields: Vec<&str> = line.split(" | ").map(str::trim).collect();
        let [family, style, file, scripts, ..] = fields.as_slice() else {
            return Err(format!("malformed manifest line: {line}"));
        };
        let path = dir.join(file).canonicalize().map_err(|error| format!("{file}: {error}"))?;
        included.push((family, style));
        println!("cargo::rerun-if-changed={}", path.display());
        let scripts: Vec<String> = scripts.split(',').map(|script| format!("{:?}", script.trim())).collect();
        let _ = writeln!(
            out,
            "    CraftFont {{ family: {family:?}, style: {style:?}, scripts: &[{}], bytes: include_bytes!({:?}) }},",
            scripts.join(", "),
            path.display().to_string(),
        );
    }
    if included.is_empty() {
        return Err("no face was selected".to_string());
    }
    Ok(out)
}
